"""
Write ROS parameter files whose values a package-provided generator script computes.

The generator script defines

    def generate(args: list[str]) -> dict[str, dict]

returning, for each output file path relative to the output directory, the ros__parameters of
'/**'. The returned files must be exactly the declared --outputs.

Usage:
    generate_param_files.py <generator_script> <output_dir> --package-dir <dir>
        --outputs <file>... [-- <generator arg>...]
"""

import argparse
import importlib.util
import os
import sys
from pathlib import Path
from typing import Any, Dict, Iterable

import yaml


class _ParamFileDumper(yaml.SafeDumper):
    pass


def _represent_str(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_ParamFileDumper.add_representer(str, _represent_str)


def display_path(value: str, package_dir: Path) -> str:
    """Host-independent form of a path argument: relative inside the package, file name outside."""
    path = Path(value)
    if not path.is_absolute():
        return value
    try:
        return str(path.resolve().relative_to(package_dir))
    except ValueError:
        return path.name


def describe_source(items: Iterable[str], package_dir: Path) -> str:
    words = []
    for item in items:
        name, sep, value = item.partition(":=")
        if sep:
            words.append(f"{name}:={display_path(value, package_dir)}")
        else:
            words.append(display_path(item, package_dir))
    return " ".join(words)


def write_param_file(path: Path, ros_parameters: Dict[str, Any], source: str):
    """Write a '/**' parameter file atomically, with a header naming its source."""
    header = f"# Generated by autoware_system_designer from {source}. Do not edit.\n"
    body = yaml.dump(
        {"/**": {"ros__parameters": ros_parameters}},
        Dumper=_ParamFileDumper,
        sort_keys=False,
        width=1000,
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = path.with_name(path.name + ".tmp")
    tmp_path.write_text(header + body)
    os.replace(tmp_path, path)


def load_generator(script: Path):
    spec = importlib.util.spec_from_file_location(f"_awsd_param_generator_{script.stem}", script)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load generator script {script}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    generate = getattr(module, "generate", None)
    if not callable(generate):
        raise AttributeError(f"{script} does not define generate(args)")
    return generate


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    generator_args = []
    if "--" in argv:
        split = argv.index("--")
        argv, generator_args = argv[:split], argv[split + 1 :]

    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("generator_script", type=Path, help="script defining generate(args)")
    parser.add_argument("output_dir", type=Path, help="directory the outputs are relative to")
    parser.add_argument("--package-dir", type=Path, required=True, help="root of the header paths")
    parser.add_argument("--outputs", nargs="+", required=True, help="declared output files")
    args = parser.parse_args(argv)

    package_dir = args.package_dir.resolve()
    generate = load_generator(args.generator_script.resolve())
    files = generate(list(generator_args))

    declared = set(args.outputs)
    returned = set(files)
    if returned != declared:
        missing = ", ".join(sorted(declared - returned)) or "-"
        extra = ", ".join(sorted(returned - declared)) or "-"
        print(
            f"{args.generator_script}: generated files differ from the declared outputs "
            f"(missing: {missing}; undeclared: {extra})",
            file=sys.stderr,
        )
        return 1

    source = describe_source([str(args.generator_script)] + generator_args, package_dir)
    for rel_path, ros_parameters in files.items():
        write_param_file(args.output_dir / rel_path, ros_parameters, source)
    return 0


if __name__ == "__main__":
    sys.exit(main())
